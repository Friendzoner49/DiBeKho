"""Write webapp/schema.js: the database schema the web page needs to make and read .dibekho packages by itself
(webapp/package.js): every migration of src/dibekho/db/migrations split exactly as db.migrate splits it, which tables
travel to the cloud and how (db/sync_schema.py), the package format. One source of truth: run this after adding a
migration or changing sync_schema; tests/test_web_package.py fails while the file is out of date.

    uv run python scripts/make_web_schema.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from dibekho import db  # noqa: E402
from dibekho.core import transfer  # noqa: E402
from dibekho.db.sync_schema import SHARED_META, SYNCED  # noqa: E402

OUT = ROOT / "webapp" / "schema.js"


def build() -> str:
    data = {
        "version": db.schema_version(),
        "format": transfer.FORMAT,
        "migrations": [[v, db._split_sql(sql)] for v, sql in db._migration_files()],
        "synced": [{"name": t.name, "key": t.key, "refs": t.refs, "natural": t.natural, "only_keys": list(t.only_keys),
                    "booleans": list(t.booleans), "timestamps": list(t.timestamps)} for t in SYNCED],
        "shared_meta": list(SHARED_META),
    }
    body = json.dumps(data, ensure_ascii=False, indent=1)
    return ("/* Generated by scripts/make_web_schema.py from the app's migrations and db/sync_schema.py -- do not edit.\n"
            "   The web makes and reads .dibekho packages with it (package.js). */\n"
            f"const DBK_SCHEMA = {body};\n"
            'if (typeof module !== "undefined") module.exports = DBK_SCHEMA;\n')


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
