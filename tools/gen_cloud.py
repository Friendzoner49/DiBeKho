# 11. joining shared data that already exists: this machine's own copy goes, everything is pulled again
scenario("start_from_cloud", [], None, op="start_from_cloud")

# ---------------------------------------------------------------- run them in Python and write what happened
blocks = []
base_conn, base_batch = build()
first_push = batch_lines(base_batch)
for name, sql, p, resolve, op, probes in SCENARIOS:
    conn, _ = build()
    for s in sql:
        conn.execute(s)
    lines = []
    if op == "start_from_cloud":
        twoway.start_from_cloud(conn)
    elif p is not None:
        merged = twoway.merge(conn, p)
        lines.append(f"merged: applied={merged.applied}|renamed={';'.join(f'{a}:{b}>{c}' for a, b, c in merged.renamed)}"
                     f"|duplicates={merged.duplicates}|separated={';'.join(merged.separated)}"
                     f"|conflicts={';'.join(c.table + ':' + c.uid for c in merged.conflicts)}"
                     f"|export={','.join(map(str, merged.receipts_to_export))}"
                     f"|files={';'.join(f'{a}:{b}' for a, b in merged.receipt_files)}")
        if resolve:
            first = twoway.conflicts(conn)[0]
            twoway.resolve(conn, first, resolve == "mine")
    if op != "start_from_cloud":
        batch, seq, hold = twoway.prepare(conn)
        lines += [f"batch: {x}" for x in batch_lines(batch)] + [f"seq: {seq}", f"hold: {','.join(sorted(f'{a}:{b}' for a, b in hold))}"]
    lines += [f"cursor: {twoway.cursor(conn)}"]
    lines += [f"conflict: {c.table}|{c.uid}|{crow(c.local)}|{crow(c.cloud)}" for c in twoway.conflicts(conn)]
    lines += [f"meta: {r[0]}={r[1]}" for r in conn.execute(
        "SELECT key, value FROM meta WHERE key NOT IN ('last_change_at', 'sync_conflicts') ORDER BY key")]
    lines += [f"probe: {conn.execute(q).fetchone()[0]}" for q in probes]
    lines += dump(conn)
    blocks.append((name, sql, json.dumps(p, ensure_ascii=False, sort_keys=True) if p is not None else "", resolve, op,
                   probes, lines))

body = ""
for name, sql, pj, resolve, op, probes, lines in blocks:
    body += ("        Scenario(\n"
             f"            name: {swift_str(name)},\n"
             f"            sql: [{', '.join(swift_str(s) for s in sql)}],\n"
             f"            pulled: {swift_str(pj)},\n"
             f"            resolve: {swift_str(resolve)}, op: {swift_str(op)},\n"
             f"            probes: [{', '.join(swift_str(s) for s in probes)}],\n"
             "            expected: [\n" + "".join(f"                {swift_str(x)},\n" for x in lines) + "            ]),\n")
(OUT / "Tests/DiBeKhoCoreTests/Generated/GoldenCloud.swift").write_text(
    HEAD + "struct CloudScenario {\n    let name: String\n    let sql: [String]  // run on the synced shop before the pull\n"
    "    let pulled: String  // what sync_pull gave (JSON), or \"\"\n    let resolve: String  // \"mine\" / \"cloud\": the first conflict is resolved\n"
    "    let op: String  // \"start_from_cloud\"\n    let probes: [String]\n    let expected: [String]\n}\n\n"
    "enum GoldenCloud {\n    /// the first push of the shop (what core.cloud.replica.pending gives after queue_all)\n"
    "    static let firstPush: [String] = [\n" + "".join(f"        {swift_str(x)},\n" for x in first_push) + "    ]\n\n"
    "    static let scenarios: [CloudScenario] = [\n" + body.replace("Scenario(", "CloudScenario(") + "    ]\n}\n",
    encoding="utf-8", newline="\n")
print(f"{len(tables)} tables, {len(SCENARIOS)} scenarios, {len(first_push)} rows in the first push, commit {commit}")
for name, *_rest, lines in blocks:
    print(" ", name, len(lines), "lines;", next((x for x in lines if x.startswith("merged")), ""))
