"""Make the Cloud files that come from the Python app (run after tools/gen_phase3.py):
    uv --project K:/HeThongSonDiBe run python -X utf8 tools/gen_cloud.py K:/HeThongSonDiBe

Writes
  Sources/DiBeKhoCore/Generated/SyncTables.swift   which tables travel to the cloud (db/sync_schema.SYNCED)
  Tests/DiBeKhoCoreTests/Generated/GoldenCloud.swift  what core/cloud/twoway.py + replica.py do on the made-up shop of
                                                      Golden.swift: first push, pulls (new rows, echo, conflict, renumbering,
                                                      duplicates, deletions, shared meta), resolving, starting from the cloud
Only made-up data goes in here; never customer data. The ids the Python code invents (uuid4) are counted from 1 so that
the Swift port, which counts the same way, gives the same ids.
"""

import copy
import json
import re
import sqlite3
import subprocess
import sys
import uuid
from pathlib import Path

SRC = Path(sys.argv[1]).resolve()
OUT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SRC / "src"))

from dibekho import db  # noqa: E402
from dibekho.core.cloud import replica, twoway  # noqa: E402
from dibekho.core.text import matches_words, unaccent  # noqa: E402
from dibekho.db import sync_schema  # noqa: E402

commit = subprocess.run(["git", "-C", str(SRC), "log", "-1", "--format=%h"], capture_output=True, text=True).stdout.strip()
HEAD = f"// GENERATED by tools/gen_cloud.py from the Python app (commit {commit}). Do not edit.\n\n"


def swift_str(s: str) -> str:
    assert "\r" not in s and "\t" not in s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def swift_list(items) -> str:
    return "[" + ", ".join(swift_str(x) for x in items) + "]"


# ---------------------------------------------------------------- the tables that travel
tables = []
for t in sync_schema.SYNCED:
    refs = ", ".join(f"{swift_str(k)}: {swift_str(v)}" for k, v in t.refs.items())
    tables.append(
        f"        SyncTable(name: {swift_str(t.name)}, key: {swift_str(t.key)}, refs: [{refs or ':'}], "
        f"natural: {'true' if t.natural else 'false'}, onlyKeys: {swift_list(t.only_keys)}, "
        f"booleans: {swift_list(t.booleans)}, timestamps: {swift_list(t.timestamps)}),\n")
# the refs of one table are looked up by column name only, so the dictionary order does not matter
(OUT / "Sources/DiBeKhoCore/Generated/SyncTables.swift").write_text(
    HEAD + "struct SyncTable {\n    let name: String\n    let key: String  // \"id\", \"rowid\" or the text key column\n"
    "    let refs: [String: String]  // column -> table it points to\n    let natural: Bool\n    let onlyKeys: [String]\n"
    "    let booleans: [String]\n    let timestamps: [String]\n}\n\n"
    "enum SyncSchema {\n    /// parents before children (pushing and applying go in this order; deleting goes backwards)\n"
    "    static let tables: [SyncTable] = [\n" + "".join(tables) + "    ]\n\n"
    f"    /// meta keys that describe the shared data\n    static let sharedMeta: [String] = {swift_list(sync_schema.SHARED_META)}\n}}\n",
    encoding="utf-8", newline="\n")

# ---------------------------------------------------------------- the scenarios, on the made-up shop
golden = (OUT / "Tests/DiBeKhoCoreTests/Generated/Golden.swift").read_text(encoding="utf-8")
SHOP = re.search(r'static let shop = #"""\n(.*?)\n"""#', golden, re.S).group(1)

counter = [0]


def fake_uuid4():
    counter[0] += 1
    return uuid.UUID(int=counter[0])


uuid.uuid4 = fake_uuid4  # replica.uid_for calls uuid.uuid4()
twoway.clock_offset = lambda: 420


def build():
    counter[0] = 0
    conn = sqlite3.connect(":memory:", isolation_level=None)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    conn.create_function("unaccent", 1, unaccent, deterministic=True)
    conn.create_function("matches_words", 2, lambda n, h: matches_words(n or "", h or ""), deterministic=True)
    db.migrate(conn)
    for statement in db._split_sql(SHOP):
        conn.execute(statement)
    for t in sync_schema.SYNCED:  # the clock times the database stamped: the same on every run
        for col in ("created_at", "closed_at"):
            if col in [r[1] for r in conn.execute(f"PRAGMA table_info({t.name})")]:
                conn.execute(f"UPDATE {t.name} SET {col} = '2026-11-01 09:00:00' WHERE {col} IS NOT NULL")
    sync_schema.ensure_triggers(conn)
    twoway.start_from_this_machine(conn)  # queue_all + cloud mode on
    batch, seq, hold = twoway.prepare(conn)
    twoway.finish(conn, seq, 100, hold)  # the first push went through
    return conn, batch


def cj(v) -> str:
    """One value as text, the same on both sides: numbers as 4-decimal floats, booleans as words."""
    if v is None:
        return "∅"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return f"{float(v):.4f}"
    return str(v)


SKIP = {"created_at", "closed_at", "at", "first_seen", "last_seen"}  # clock times: not the same on every run


def crow(row: dict) -> str:
    return "|".join(f"{k}={cj(row[k])}" for k in sorted(row) if k not in SKIP)


def batch_lines(batch: dict) -> list[str]:
    return [f"{t}: {crow(r)}" for t in batch for r in batch[t]]


DUMPED = [t.name for t in sync_schema.SYNCED] + ["scanned_files"]


def dump(conn) -> list[str]:
    out = []
    for name in DUMPED:
        cols = [r[1] for r in conn.execute(f"PRAGMA table_info({name})") if r[1] not in SKIP]
        only = " WHERE key != 'sync_conflicts'" if name == "meta" else ""  # its JSON text differs in key order between the languages
        for r in conn.execute(f"SELECT {', '.join(cols)} FROM {name}{only} ORDER BY rowid"):
            out.append(f"{name}: " + "|".join(f"{c}={cj(r[c])}" for c in cols))
    out += [f"sync_map: {r[0]}|{r[1]}|{r[2]}" for r in conn.execute("SELECT tbl, local_id, uid FROM sync_map ORDER BY tbl, local_id")]
    out += [f"outbox: {r[0]}|{r[1]}|{r[2]}|{cj(r[3])}" for r in conn.execute("SELECT tbl, local_id, op, uid FROM sync_outbox ORDER BY seq")]
    out += [f"flag: {r[0]}={r[1]}" for r in conn.execute("SELECT key, value FROM sync_flags ORDER BY key")]
    return out


def uid(conn, table, local_id):
    return replica.uid_for(conn, table, local_id, create=False)


def clone(conn, table, local_id, **over):
    """A cloud row made from a local one (what another machine would have written), under a new id."""
    t = sync_schema.BY_NAME[table]
    row = conn.execute(f"SELECT {'rowid AS _rowid, ' if t.key == 'rowid' else ''}* FROM {table} "
                       f"WHERE {'rowid' if t.key == 'rowid' else t.key} = ?", (local_id,)).fetchone()
    cloud = replica.to_cloud(conn, t, row)
    cloud.update(over)
    return cloud


def pulled(max_rev=101, **tables_):
    return {"tables": tables_, "max_rev": max_rev}


SCENARIOS = []  # (name, sql, pulled, resolve, op, probes)


def scenario(name, sql, make_pulled, resolve="", op="", probes=()):
    conn, _ = build()
    for s in sql:
        conn.execute(s)
    p = make_pulled(conn) if make_pulled else None
    SCENARIOS.append((name, sql, p, resolve, op, list(probes)))


# 1. rows another machine wrote: new product + new customer, timestamps as Postgres writes them
scenario("new_from_cloud", [], lambda c: pulled(
    products=[clone(c, "products", 1, id="00000000-0000-0000-0000-00000000f001", code="SP005", name_vi="Sơn mới",
                    created_at="2026-11-02T10:00:00")],
    customers=[clone(c, "customers", 2, id="00000000-0000-0000-0000-00000000f002", name="Khách từ web",
                     created_at="2026-11-02T10:00:01")]),
         probes=["SELECT created_at FROM products WHERE code = 'SP005'"])

# 2. our own earlier push whose answer was lost: the cloud's row equals the queued local one -> nothing to do
def echo(c):
    row = clone(c, "products", 1)
    return pulled(products=[row])
scenario("echo", ["UPDATE products SET name_vi = 'Sơn đã sửa' WHERE id = 1"], echo)

# 3. both sides changed the same row: a conflict, nothing applied, nothing pushed for it
scenario("conflict", ["UPDATE products SET name_vi = 'Sơn của máy này' WHERE id = 1"],
         lambda c: pulled(products=[clone(c, "products", 1, name_vi="Sơn của máy khác")]))
scenario("conflict_keep_mine", ["UPDATE products SET name_vi = 'Sơn của máy này' WHERE id = 1"],
         lambda c: pulled(products=[clone(c, "products", 1, name_vi="Sơn của máy khác")]), resolve="mine")
scenario("conflict_keep_cloud", ["UPDATE products SET name_vi = 'Sơn của máy này' WHERE id = 1"],
         lambda c: pulled(products=[clone(c, "products", 1, name_vi="Sơn của máy khác")]), resolve="cloud")

# 4. the same product code handed out on two machines: ours is renumbered here
scenario("renumber_product",
         ["INSERT INTO products(id, code, name_vi, unit, active) VALUES (5, 'SP005', 'Hàng của máy này', 'cái', 1)"],
         lambda c: pulled(products=[clone(c, "products", 1, id="00000000-0000-0000-0000-00000000f003", code="SP005",
                                         name_vi="Hàng của máy khác")]))

# 5. the same receipt code on two machines: ours is renumbered and its Excel file must follow
scenario("renumber_receipt",
         ["INSERT INTO documents(id, kind, code, code_norm, doc_date, status, location_id, location_set, receipt_source, source_file) "
          "VALUES (20, 'receipt', 'HV003', 'HV003', '2026-11-10', 'active', 1, 1, 'supplier', 'HV003.xlsx')"],
         lambda c: pulled(documents=[clone(c, "documents", 6, id="00000000-0000-0000-0000-00000000f004", code="HV003",
                                          code_norm="HV003", doc_date="2026-11-11")]))

# 6. the same delivery note (same file) read on both machines: the cloud's stays, ours goes
DELIVERY = ("INSERT INTO documents(id, kind, code, code_norm, doc_date, customer_id, status, source_file, source_hash, "
            "location_id, location_set) VALUES (20, 'delivery', '080', '80', '2026-11-10', 1, 'active', 'phieu-80.xlsx', '{h}', 1, 1)")
