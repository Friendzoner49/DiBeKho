def swift_str(s: str) -> str:
    assert "\n" not in s and "\r" not in s and "\t" not in s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


# ---------------------------------------------------------------- migrations
files = sorted((SRC / "src" / "dibekho" / "db" / "migrations").glob("*.sql"))
parts = []
for f in files:
    text = f.read_text(encoding="utf-8").replace("\r\n", "\n")
    assert '"""#' not in text
    sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
    version = int(f.name.split("_", 1)[0])
    parts.append(f'        // {f.name}  sha256 {sha}\n'
                 f'        Migration(version: {version}, name: {swift_str(f.name)}, sql: #"""\n{text}\n"""#),\n')
