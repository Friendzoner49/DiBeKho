def canon(value) -> str:
    """One value as both sides print it: numbers with 4 decimals, nothing as ∅."""
    if value is None:
        return "∅"
    if isinstance(value, (int, float)):
        return f"{float(value):.4f}"
    return str(value)


def line(row, keys) -> str:
    get = row.__getitem__ if isinstance(row, (sqlite3.Row, dict)) else (lambda k: getattr(row, k))
    return "|".join(f"{k}={canon(get(k))}" for k in keys)


