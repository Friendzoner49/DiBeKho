def inbox_text(item) -> str:
    message = item.error
    if message.startswith("Không phải file hàng về hay"):
        message = "NOT_RECEIPT"
    elif message.startswith("Không mở được file Excel") or "not a zip" in message:
        message = "Không mở được file Excel"
    detail = ""
    if item.receipt is not None:
        detail = f"{item.receipt.doc_date}|{item.receipt.note}|" + ",".join(
            f"{ln.row}:{ln.code}:{canon(ln.qty)}:{'-' if p is None else p['id']}" for ln, p in item.resolved or []
        ) + "|" + "/".join(item.receipt.warnings)
    return f"{item.path.name}|{item.kind}|{message}|{detail}"


