def doc_line(doc_id: int) -> str:
    d = conn.execute("SELECT d.*, COALESCE(c.name, '') AS customer FROM documents d LEFT JOIN customers c "
                     "ON c.id = d.customer_id WHERE d.id = ?", (doc_id,)).fetchone()
    lines = conn.execute("SELECT product_id, qty, unit_price, amount, note FROM document_lines WHERE document_id = ? "
                         "ORDER BY line_no", (doc_id,)).fetchall()
    moves = conn.execute("SELECT product_id, location_id, qty FROM stock_movements WHERE document_id = ? ORDER BY id",
                         (doc_id,)).fetchall()
    return (f"{d['code']}|{d['doc_date']}|{d['status']}|{d['customer']}|{d['source_file']}|{canon(d['location_set'])}"
            + "|L:" + ",".join(f"{r[0]}:{canon(r[1])}:{canon(r[2])}:{canon(r[3])}:{r[4]}" for r in lines)
            + "|M:" + ",".join(f"{r[0]}/{r[1]}:{canon(r[2])}" for r in moves))


