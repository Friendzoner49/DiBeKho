def stamp_free(name: str) -> str:
    return re.sub(r"__\d{8}-\d{6}", "__T", name)


def layout() -> str:
    items = sorted(p.relative_to(ws.root).as_posix() for p in ws.root.rglob("*")
                   if p.is_file() and not p.relative_to(ws.root).as_posix().startswith(("data/", "sao-luu/")))
    return ",".join(stamp_free(i) for i in items)


