def swift_str(s: str) -> str:
    assert "\r" not in s and "\t" not in s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main() -> int:
    # the Swift app embeds the same i18n texts (tools/gen_phase3.py); a difference would change the title check
    strings = (OUT / "Sources/DiBeKhoCore/Generated/Strings.swift").read_text(encoding="utf-8")
    for lang in ("vi", "en", "zh"):
        py = json.loads((SRC / "src/dibekho/i18n" / f"{lang}.json").read_text(encoding="utf-8"))
        start = strings.index(f'"{lang}": #"""\n') + len(f'"{lang}": #"""\n')
        swift = json.loads(strings[start:strings.index('\n"""#', start)])
        if py != swift:
            print(f"i18n/{lang}.json differs from Strings.swift: run tools/gen_phase3.py first")
            return 1
    # gzip as the Python app writes the cloud backups (gzip.compress: an mtime and an OS byte in the header), so the
    # Swift gunzip is tested on Python's bytes, not only on its own; and a whole backup of a made-up shop
    sample = ("DiBeKho sao lưu thử · " * 300 + "".join(chr(0x4E00 + i) for i in range(400))).encode("utf-8")
    sample_gz = gzip.compress(sample, compresslevel=6, mtime=1_794_389_400)
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "kho.sqlite"
        conn = db.connect(path)
        with db.transaction(conn):
            conn.execute("INSERT INTO customers(name, phone) VALUES ('Khách Mẫu', '0900000001')")
            conn.execute("INSERT INTO scanned_files(hash, rel_path, status) VALUES ('h1', 'phieu-giao-hang/a.xlsx', 'imported')")
        schema = conn.execute("PRAGMA user_version").fetchone()[0]
        conn.close()
        backup_gz = gzip.compress(path.read_bytes(), compresslevel=6, mtime=1_794_389_400)
    days = logs.anonymize(LOG)
    titles = sorted(logs._app_titles())
    digest = hashlib.sha1("\n".join(titles).encode("utf-8")).hexdigest()
    out = [f"// GENERATED by tools/gen_logs.py from the Python app (commit {commit}). Do not edit.\n",
           "enum GoldenLogs {",
           f"    static let log = {swift_str(LOG)}",
           "    /// core/cloud/logs.anonymize(log)",
           "    static let days: [String: String] = ["]
    out += [f"        {swift_str(day)}: {swift_str(text)}," for day, text in sorted(days.items())]
    out += ["    ]",
            "    /// logs._app_titles(): how many and the sha1 of the sorted titles joined by newlines",
            f"    static let titleCount = {len(titles)}",
            f"    static let titleHash = {swift_str(digest)}",
            "    /// gzip.compress(sample) by Python, and the sha256 of the sample",
            f"    static let sampleGz = {swift_str(base64.b64encode(sample_gz).decode())}",
            f"    static let sampleSha256 = {swift_str(hashlib.sha256(sample).hexdigest())}",
            "    /// a cloud backup as the Python app uploads it: kho.sqlite of a made-up shop (one customer, one note read)",
            f"    static let backupGz = {swift_str(base64.b64encode(backup_gz).decode())}",
            f"    static let backupSchema = {schema}",
            "}", ""]
    path = OUT / "Tests/DiBeKhoCoreTests/Generated/GoldenLogs.swift"
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("written:", path.name, len(days), "days,", len(titles), "titles")
    for day, text in sorted(days.items()):
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
