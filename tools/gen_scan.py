def _mac_order(ws):
    """The notes in the order the Python app reads them on a Mac: names compared letter by letter, capitals first.
    (Windows compares paths ignoring case, which would put 'Tháng 11/…' after 'n155.xlsx'; the Swift app is for Macs.)"""
    files = [p for p in ws.deliveries.rglob("*")
             if p.is_file() and p.suffix.lower() == ".xlsx" and not p.name.startswith(("~$", "."))]
    return sorted(files, key=lambda p: p.relative_to(ws.deliveries).parts)


