"""Make the phase 3 Swift files that come from the Python app (run after tools/gen_from_python.py):
    uv --project K:/HeThongSonDiBe run python -X utf8 tools/gen_phase3.py K:/HeThongSonDiBe

Writes
  Sources/DiBeKhoCore/Generated/SyncTriggers.swift  the sync triggers (db/sync_schema.trigger_sql), created on every
                                                     open exactly as the Python app does (db.connect)
  Sources/DiBeKhoCore/Generated/Strings.swift       the screen texts vi / en / zh (i18n/*.json), so every button and
                                                     page has the Python app's own name
  Tests/DiBeKhoCoreTests/Generated/GoldenWrites.swift  what the Python core writes for a fixed list of operations on
                                                     the made-up shop of Golden.swift (every table, row by row)
Only made-up data goes in here; never customer data.
"""

import re
import sqlite3
import subprocess
import sys
from datetime import date
from pathlib import Path

SRC = Path(sys.argv[1]).resolve()
OUT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SRC / "src"))

from dibekho import db  # noqa: E402
from dibekho.core import catalog, receipts, stock  # noqa: E402
from dibekho.core.receipts import NewProduct, ReceiptInput, ReceiptLineInput  # noqa: E402
