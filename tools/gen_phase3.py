from dibekho.core.text import matches_words, unaccent  # noqa: E402
from dibekho.db import sync_schema  # noqa: E402

commit = subprocess.run(["git", "-C", str(SRC), "log", "-1", "--format=%h"], capture_output=True, text=True).stdout.strip()
HEAD = f"// GENERATED by tools/gen_phase3.py from the Python app (commit {commit}). Do not edit.\n\n"


def swift_str(s: str) -> str:
    assert "\r" not in s and "\t" not in s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


# ---------------------------------------------------------------- sync triggers
statements = [s for t in sync_schema.SYNCED for s in sync_schema.trigger_sql(t)]
(OUT / "Sources/DiBeKhoCore/Generated/SyncTriggers.swift").write_text(
    HEAD + "enum SyncTriggers {\n    /// db/sync_schema.trigger_sql for every table of SYNCED, in order\n"
    "    static let statements: [String] = [\n" + "".join(f"        {swift_str(s)},\n" for s in statements)
    + "    ]\n}\n", encoding="utf-8", newline="\n")

# ---------------------------------------------------------------- screen texts
parts = []
for lang in ("vi", "en", "zh"):
    text = (SRC / "src/dibekho/i18n" / f"{lang}.json").read_text(encoding="utf-8").replace("\r\n", "\n")
    assert '"#' not in text
    parts.append(f'        "{lang}": #"""\n{text}\n"""#,\n')
(OUT / "Sources/DiBeKhoCore/Generated/Strings.swift").write_text(
    HEAD + "enum StringFiles {\n    /// i18n/{vi,en,zh}.json of the Python app, word for word\n"
    "    static let json: [String: String] = [\n" + "".join(parts) + "    ]\n}\n", encoding="utf-8", newline="\n")

# ---------------------------------------------------------------- the operations, on the made-up shop
golden = (OUT / "Tests/DiBeKhoCoreTests/Generated/Golden.swift").read_text(encoding="utf-8")
SHOP = re.search(r'static let shop = #"""\n(.*?)\n"""#', golden, re.S).group(1)

conn = sqlite3.connect(":memory:", isolation_level=None)
conn.row_factory = sqlite3.Row
conn.execute("PRAGMA foreign_keys = ON")
conn.create_function("unaccent", 1, unaccent, deterministic=True)
conn.create_function("matches_words", 2, lambda n, h: matches_words(n or "", h or ""), deterministic=True)
db.migrate(conn)
for statement in db._split_sql(SHOP):
    conn.execute(statement)
sync_schema.ensure_triggers(conn)
conn.execute("UPDATE sync_flags SET value = '1' WHERE key = 'enabled'")  # cloud mode: every write is queued
db.set_meta(conn, "freed_codes", "SP010,SP008")
db.set_meta(conn, "product_code_max", "4")

checks: list[str] = []  # values the functions return along the way, one line each


def canon(value) -> str:
    if value is None:
        return "∅"
    if isinstance(value, (int, float)):
        return f"{float(value):.4f}"
    return str(value)


def run(name, fn):
    try:
        result = fn()
        checks.append(f"{name}={canon(result)}")
    except ValueError as e:
        checks.append(f"{name}!{e}")


def tx(fn):
    def go():
        with db.transaction(conn):
            return fn()
    return go


