touched = db.get_meta(conn, "last_change_at")
assert re.fullmatch(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d", touched), touched

SKIP = {"created_at", "closed_at", "at"}
TABLES = ["products", "customers", "suppliers", "documents", "document_lines", "stock_movements", "meta", "app_log",
          "sync_outbox", "sync_map"]
dump: dict[str, list[str]] = {}
for t in TABLES:
    cols = [r[1] for r in conn.execute(f"PRAGMA table_info({t})") if r[1] not in SKIP]
    rows = conn.execute(f"SELECT {', '.join(cols)} FROM {t} ORDER BY rowid").fetchall()
    dump[t] = ["|".join(f"{c}={canon(r[c] if not (t == 'meta' and c == 'value' and r['key'] == 'last_change_at') else 'T')}"
                        for c in cols) for r in rows]

body = "".join(f"        {swift_str(k)}: [\n" + "".join(f"            {swift_str(x)},\n" for x in v) + "        ],\n"
               for k, v in dump.items())
(OUT / "Tests/DiBeKhoCoreTests/Generated/GoldenWrites.swift").write_text(
    HEAD + "enum GoldenWrites {\n"
    "    /// what each step returned (name=value) or the error it raised (name!message)\n"
    "    static let checks: [String] = [\n" + "".join(f"        {swift_str(c)},\n" for c in checks) + "    ]\n\n"
    "    /// every table after the steps, rows in rowid order, times left out (last_change_at shown as T)\n"
    "    static let tables: [String: [String]] = [\n" + body + "    ]\n}\n", encoding="utf-8", newline="\n")
print(f"{len(statements)} triggers, 3 string files, {len(checks)} checks, "
      f"{sum(len(v) for v in dump.values())} rows, from commit {commit}")
for c in checks:
    print(" ", c)
