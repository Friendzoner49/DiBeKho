/** The page's language: the one chosen before (kept in this browser), else the browser's own (Chinese -> 中文). */
let LANG = (() => {
  try {
    const kept = window.localStorage.getItem(LANG_KEY);
    if (LANGS.includes(kept)) return kept;
  } catch (e) { /* storage blocked: the browser's language */ }
  return typeof navigator !== "undefined" && /^zh/i.test(navigator.language || "") ? "zh" : "vi";
})();

/** The text of a key in the page's language, {name} filled in from vars; a missing key falls back to Vietnamese. */
function tr(key, vars) {
  let s = WEB_TEXT[LANG][key] ?? WEB_TEXT.vi[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

/** Every fixed text of the page (data-i18n = text, data-i18n-ph = placeholder, data-i18n-title = tooltip). */
function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = tr(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = tr(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = tr(el.dataset.i18nTitle); });
  document.documentElement.lang = LANG === "zh" ? "zh-CN" : "vi";
}

/** Switch the language: kept in this browser, the page opens again in it (the sign-in stays). */
function setLang(lang) {
  if (!LANGS.includes(lang) || lang === LANG) return;
  try { window.localStorage.setItem(LANG_KEY, lang); } catch (e) { /* not kept: this time only */ }
  LANG = lang;
  location.reload();
}

if (typeof module !== "undefined") module.exports = { WEB_TEXT, LANGS };
